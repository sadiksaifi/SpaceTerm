/// One captured foreground action. Providers validate it after every await and before an effect.
/// The pointer identity, not just a reused counter, binds completions to their originating sheet.
#[derive(Clone)]
pub(crate) struct EnrollmentAttempt {
    generation: u64,
    valid: Arc<AtomicBool>,
}
impl EnrollmentAttempt {
    pub(crate) fn new(generation: u64) -> Self {
        Self {
            generation,
            valid: Arc::new(AtomicBool::new(true)),
        }
    }
    pub(crate) fn generation(&self) -> u64 {
        self.generation
    }
    pub(crate) fn validate(&self) -> Result<(), EnrollmentFailure> {
        if self.valid.load(Ordering::Acquire) {
            Ok(())
        } else {
            Err(PairingFailure::Cancelled.into())
        }
    }
    fn matches(&self, other: &Self) -> bool {
        self.generation == other.generation
            && Arc::ptr_eq(&self.valid, &other.valid)
            && self.validate().is_ok()
    }
    fn cancel(&self) {
        self.valid.store(false, Ordering::Release);
    }
}

/// The invitation is transient bearer delivery from an already authorized owner/device. It must
/// never be generated by the client or persisted in the Settings Document or client journal.
pub(crate) enum EnrollmentTarget {
    Direct {
        address: String,
        invitation: Zeroizing<String>,
    },
    Ssh {
        host: String,
    },
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum EnrollmentFailure {
    Pairing(PairingFailure),
    Bootstrap(BootstrapFailureClass),
    ProviderUnavailable,
    CredentialStorageLocked,
    BootstrapUnresolved(BootstrapRequest),
}
impl From<PairingFailure> for EnrollmentFailure {
    fn from(value: PairingFailure) -> Self {
        Self::Pairing(value)
    }
}
impl From<BootstrapFailure> for EnrollmentFailure {
    fn from(value: BootstrapFailure) -> Self {
        Self::Bootstrap(value.class)
    }
}

/// Bounded identity of an already published native request. It grants lookup only.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct BootstrapRequest {
    request: [u8; 16],
    artifact: [u8; 32],
}
impl BootstrapRequest {
    pub(crate) fn new(request: [u8; 16], artifact: [u8; 32]) -> Result<Self, EnrollmentFailure> {
        if request == [0; 16] || artifact == [0; 32] {
            return Err(PairingFailure::InvalidRequest.into());
        }
        Ok(Self { request, artifact })
    }
    pub(crate) fn request(self) -> [u8; 16] {
        self.request
    }
    pub(crate) fn artifact(self) -> [u8; 32] {
        self.artifact
    }
}

/// All fields are public-only except the zeroizing, move-only bearer authorization. Construction
/// checks the exact native credential, reservation, pin and route before the sheet presents them.
pub(crate) struct DirectCandidate {
    attempt: EnrollmentAttempt,
    prepared: PreparedEnrollment,
    device: PreparedCredential,
    reservation: PublicEnrollmentReservation,
    authorization: Option<EnrollmentAuthorization>,
    majors: Vec<u32>,
    native_route: Option<spaceterm_client::api::RouteDescription>,
}
impl DirectCandidate {
    pub(crate) fn new(
        attempt: EnrollmentAttempt,
        prepared: PreparedEnrollment,
        device: PreparedCredential,
        reservation: PublicEnrollmentReservation,
        authorization: Option<EnrollmentAuthorization>,
        majors: Vec<u32>,
    ) -> Result<Self, EnrollmentFailure> {
        attempt.validate()?;
        prepared.validate()?;
        let p = reservation.parts();
        if prepared.reservation.as_ref() != Some(&reservation)
            || p.target.parts().server.bytes() != prepared.pin.identity
            || p.target.parts().pairing != prepared.local_pairing.parts().pairing
            || p.target.parts().device != prepared.device
            || p.keys != prepared.keys
            || p.initial_client != prepared.client
            || p.enrollment_stream != prepared.enrollment.id.stream()
            || p.enrollment_request_digest != prepared.enrollment.digest
            || device.scope.parts().purpose != CredentialPurpose::DeviceIdentity
            || device.scope.parts().namespace != prepared.credential.scope.parts().namespace
            || device.public_key != prepared.keys.parts().device_identity_public_key
        {
            return Err(PairingFailure::IdentityMismatch.into());
        }
        if majors.is_empty()
            || majors.len() > 2
            || majors.iter().any(|major| !matches!(major, 1 | 2))
        {
            return Err(PairingFailure::Incompatible.into());
        }
        Ok(Self {
            attempt,
            prepared,
            device,
            reservation,
            authorization,
            majors,
            native_route: None,
        })
    }
    fn verifier(&self) -> Result<DirectEnrollmentAttempt, EnrollmentFailure> {
        Ok(DirectEnrollmentAttempt::new(
            self.prepared.pin,
            self.prepared.route,
            self.attempt.generation,
        )?)
    }
    fn approve(
        &mut self,
        verifier: &DirectEnrollmentAttempt,
        compared: &str,
    ) -> Result<DirectApproval, EnrollmentFailure> {
        self.attempt.validate()?;
        let verified = verifier.confirm(
            self.prepared.pin,
            self.prepared.route,
            self.attempt.generation,
            compared,
        )?;
        Ok(DirectApproval {
            attempt: self.attempt.clone(),
            verified,
            prepared: self.prepared.clone(),
            device: self.device.clone(),
            reservation: self.reservation.clone(),
            authorization: self.authorization.take(),
            majors: self.majors.clone(),
            native_route: self.native_route.clone(),
        })
    }
}

/// A single comparison and single use of the bearer. Rechecking a lost reply retains the original
/// reservation and native reference and has no bearer; EnrollmentDriver performs exact lookup.
pub(crate) struct DirectApproval {
    attempt: EnrollmentAttempt,
    verified: VerifiedServer,
    prepared: PreparedEnrollment,
    device: PreparedCredential,
    reservation: PublicEnrollmentReservation,
    authorization: Option<EnrollmentAuthorization>,
    majors: Vec<u32>,
    native_route: Option<spaceterm_client::api::RouteDescription>,
}
impl DirectApproval {
    /// Production providers use the existing enrollment driver and canonical pairing store.
    /// This does not create a second journal, native credential provider or transport scheduler.
    pub(crate) async fn enroll<
        S: LocalPairingStore,
        N: NativeDeviceCredentials,
        R: EnrollmentConnector,
    >(
        self,
        driver: &EnrollmentDriver<S, N, R>,
        store: &dyn LocalPairingStore,
    ) -> Result<DurableEnrollment, EnrollmentFailure> {
        self.attempt.validate()?;
        let saved = driver
            .enroll(EnrollmentAttemptRequest {
                verified: &self.verified,
                prepared: &self.prepared,
                device: &self.device,
                reservation: self.reservation,
                authorization: self.authorization.as_ref(),
                majors: self.majors,
            })
            .await?;
        self.attempt.validate()?;
        DurableEnrollment::verify(self.attempt, store, self.prepared, saved).await
    }
}

/// No unverified receipt or successful network reply can enter the server list. Only this
/// verifier can construct the publication input, after the canonical journal reports it active.
pub(crate) struct DurableEnrollment {
    attempt: EnrollmentAttempt,
    bootstrap: Option<BootstrapOutcome>,
    prepared: PreparedEnrollment,
    saved: SavedPairing,
    handle: Option<spaceterm_client::registry::ServerHandle>,
    pub(crate) settings: Option<super::server_runtime::SettingsServices>,
}
impl DurableEnrollment {
    pub(crate) async fn verify(
        attempt: EnrollmentAttempt,
        store: &dyn LocalPairingStore,
        prepared: PreparedEnrollment,
        saved: SavedPairing,
    ) -> Result<Self, EnrollmentFailure> {
        attempt.validate()?;
        prepared.validate()?;
        if verify_binding(&prepared, saved.receipt().clone(), false)? != saved {
            return Err(PairingFailure::IdentityMismatch.into());
        }
        let recovered = store.recover().await?;
        if recovered.active(saved.key()) != Some(&saved) {
            return Err(PairingFailure::InvalidDurableState.into());
        }
        // A synchronous self-unpair fence can precede its durable tombstone. Historical
        // receipt presence must not turn that pairing into ordinary authority again.
        let _ordinary = store.ordinary_authority(saved.key()).await?;
        attempt.validate()?;
        Ok(Self {
            attempt,
            bootstrap: None,
            prepared,
            saved,
            handle: None,
            settings: None,
        })
    }
    /// The server and route are the verified BootstrapCoordinator result, not UI-discovered claims.
    pub(crate) async fn verify_bootstrap(
        attempt: EnrollmentAttempt,
        store: &dyn LocalPairingStore,
        prepared: PreparedEnrollment,
        saved: SavedPairing,
        outcome: BootstrapOutcome,
    ) -> Result<Self, EnrollmentFailure> {
        if outcome.phase != BootstrapPhase::Connected || outcome.server.pin != saved.pin() {
            return Err(PairingFailure::IdentityMismatch.into());
        }
        let mut enrollment = Self::verify(attempt, store, prepared, saved).await?;
        enrollment.bootstrap = Some(outcome);
        Ok(enrollment)
    }
    pub(crate) fn saved(&self) -> &SavedPairing {
        &self.saved
    }
}

#[derive(Clone)]
pub(crate) struct SshCandidate {
    attempt: EnrollmentAttempt,
    facts: BootstrapHostFacts,
    pending: Option<BootstrapRequest>,
    confirmation: Arc<std::sync::Mutex<Option<BootstrapAttempt>>>,
}
impl SshCandidate {
    pub(crate) fn attempt(&self) -> EnrollmentAttempt {
        self.attempt.clone()
    }
    pub(crate) fn facts(&self) -> BootstrapHostFacts {
        self.facts
    }
    pub(crate) fn new(
        attempt: EnrollmentAttempt,
        facts: BootstrapHostFacts,
    ) -> Result<Self, EnrollmentFailure> {
        attempt.validate()?;
        if facts.route.account_uid() != facts.account_uid {
            return Err(PairingFailure::RouteChanged.into());
        }
        // Check platform/manager even for a stopped installation. No Start is offered on a host
        // whose native prerequisites cannot uphold account-service guarantees.
        facts.supported_platform()?;
        facts.prerequisites(matches!(facts.registration, BootstrapRegistration::Missing))?;
        match facts.registration {
            BootstrapRegistration::Running {
                pin,
                generation,
                artifact_identity,
                protocol_majors,
                ..
            } => {
                if pin.identity == [0; 16]
                    || pin.public_key == [0; 32]
                    || generation == 0
                    || artifact_identity == [0; 32]
                {
                    return Err(PairingFailure::InvalidDurableState.into());
                }
                if !protocol_majors.iter().any(|major| matches!(major, 1 | 2)) {
                    return Err(PairingFailure::Incompatible.into());
                }
            }
            BootstrapRegistration::Stopped { pin, generation } => {
                if pin.identity == [0; 16] || pin.public_key == [0; 32] || generation == 0 {
                    return Err(PairingFailure::InvalidDurableState.into());
                }
            }
            BootstrapRegistration::Locked => {
                return Err(EnrollmentFailure::Bootstrap(
                    BootstrapFailureClass::StorageLocked,
                ));
            }
            BootstrapRegistration::Unavailable => {
                return Err(PairingFailure::StorageUnavailable.into());
            }
            BootstrapRegistration::Missing => (),
        }
        Ok(Self {
            attempt,
            facts,
            pending: None,
            confirmation: Arc::new(std::sync::Mutex::new(None)),
        })
    }
    /// Native recovery supplies the original request; reopening a sheet cannot issue a replacement.
    pub(crate) fn retain_request(
        mut self,
        pending: BootstrapRequest,
    ) -> Result<Self, EnrollmentFailure> {
        if matches!(self.facts.registration, BootstrapRegistration::Running { artifact_identity, .. } if artifact_identity != pending.artifact)
        {
            return Err(PairingFailure::IdentityMismatch.into());
        }
        self.pending = Some(pending);
        Ok(self)
    }
    fn confirm(&self) -> Result<DeliberateBootstrap, EnrollmentFailure> {
        self.attempt.validate()?;
        if self.pending.is_some() {
            return Err(PairingFailure::RecoveryRequired.into());
        }
        if matches!(
            self.facts.registration,
            BootstrapRegistration::Stopped { .. }
        ) {
            return Err(PairingFailure::ExplicitStartRequired.into());
        }
        let mut confirmation = self
            .confirmation
            .lock()
            .map_err(|_| PairingFailure::InvalidDurableState)?;
        if confirmation.is_some() {
            return Err(PairingFailure::RecoveryRequired.into());
        }
        let intent = ForegroundBootstrap::confirm_observed(self.facts, self.attempt.generation)?;
        *confirmation = Some(intent.cancellation());
        Ok(intent)
    }
}

pub(crate) enum EnrollmentDiscovery {
    Direct(Box<DirectCandidate>),
    Ssh(Box<SshCandidate>),
}

/// Constructor-injected native services, shared with the application's one client journal.
/// Inspection is read-only on the server. It may reserve native client credentials, but may not
/// install, Start, enroll, update, connect ordinarily or publish. Providers capture address/SSH
/// configuration once, and reject changed native routes rather than reinterpret user text.
pub(crate) trait EnrollmentProvider {
    fn inspect(
        &self,
        target: EnrollmentTarget,
        attempt: EnrollmentAttempt,
        cx: &mut App,
    ) -> Task<Result<EnrollmentDiscovery, EnrollmentFailure>>;
    fn enroll_direct(
        &self,
        approval: DirectApproval,
        cx: &mut App,
    ) -> Task<Result<DurableEnrollment, EnrollmentFailure>>;
    /// Runs BootstrapCoordinator with the supplied intent, then verifies its binding in the
    /// canonical journal through DurableEnrollment::verify. No bootstrap/reconnect fallback.
    fn bootstrap(
        &self,
        intent: DeliberateBootstrap,
        candidate: SshCandidate,
        cx: &mut App,
    ) -> Task<Result<DurableEnrollment, EnrollmentFailure>>;
    /// Looks up only the original native request and retained pairing receipt. It must never
    /// authorize another owner request, install, Start, update or issue a replacement pairing.
    fn resolve_bootstrap(
        &self,
        candidate: SshCandidate,
        request: BootstrapRequest,
        cx: &mut App,
    ) -> Task<Result<DurableEnrollment, EnrollmentFailure>>;
    /// Separate explicit Start. The exact stopped registration and route must still match.
    /// It does not enroll. The person must Check Again and confirm setup afterwards.
    fn start(&self, candidate: SshCandidate, cx: &mut App) -> Task<Result<(), EnrollmentFailure>>;
    /// Revalidates journal authority synchronously and adds only this durable saved binding to
    /// the existing runtime. Cancellation/stale completion never calls this method.
    fn publish(&self, enrollment: DurableEnrollment, cx: &mut App)
    -> Result<(), EnrollmentFailure>;
}

pub(crate) struct InstalledEnrollment(pub(crate) Rc<dyn EnrollmentProvider>);
impl Global for InstalledEnrollment {}
/// Called once by desktop composition with native credentials, the canonical journal and routes.
pub(crate) fn install(provider: Rc<dyn EnrollmentProvider>, cx: &mut App) {
    cx.set_global(InstalledEnrollment(provider));
}

#[derive(Clone, Copy, Eq, PartialEq)]
enum Method {
    Direct,
    Ssh,
}
enum Candidate {
    Direct {
        candidate: Box<DirectCandidate>,
        verifier: DirectEnrollmentAttempt,
        submitted: bool,
    },
    Ssh(Box<SshCandidate>),
}
struct ServerEnrollment {
    provider: Option<Rc<dyn EnrollmentProvider>>,
    method: Method,
    address: Entity<TextInput>,
    invitation: Entity<TextInput>,
    comparison: Entity<TextInput>,
    generation: u64,
    attempt: Option<EnrollmentAttempt>,
    bootstrap_attempt: Option<BootstrapAttempt>,
    ssh_submitted: bool,
    candidate: Option<Candidate>,
    busy: bool,
    done: bool,
    status: SharedString,
    operation: Option<Task<()>>,
}
impl Drop for ServerEnrollment {
    fn drop(&mut self) {
        if let Some(attempt) = &self.attempt {
            attempt.cancel();
        }
        if let Some(attempt) = &self.bootstrap_attempt {
            attempt.cancel();
        }
    }
}
impl ServerEnrollment {
    fn new(window: &mut Window, cx: &mut Context<Self>) -> Self {
        let address = input(
            "settings-server-enrollment-address",
            "Server address or SSH host",
            false,
            window,
            cx,
        );
        let invitation = input(
            "settings-server-enrollment-invitation",
            "Single-use pairing invitation",
            true,
            window,
            cx,
        );
        let comparison = input(
            "settings-server-enrollment-comparison",
            "Fingerprint from the server's owner",
            false,
            window,
            cx,
        );
        for field in [&address, &invitation] {
            cx.subscribe(field, |sheet, _, event: &TextInputEvent, cx| {
                if matches!(event, TextInputEvent::ValueChanged(_)) {
                    sheet.cancel(cx);
                    cx.notify();
                }
            })
            .detach();
        }
        cx.subscribe(&comparison, |_, _, _: &TextInputEvent, cx| cx.notify())
            .detach();
        let provider = cx
            .try_global::<InstalledEnrollment>()
            .map(|installed| installed.0.clone());
        Self {
            status: if provider.is_some() {
                "Enter an address and a single-use invitation from an already paired device.".into()
            } else {
                failure_message(EnrollmentFailure::ProviderUnavailable).into()
            },
            provider,
            method: Method::Direct,
            address,
            invitation,
            comparison,
            generation: 0,
            attempt: None,
            bootstrap_attempt: None,
            ssh_submitted: false,
            candidate: None,
            busy: false,
            done: false,
            operation: None,
        }
    }
    fn cancel(&mut self, cx: &mut Context<Self>) {
        if let Some(attempt) = self.attempt.take() {
            attempt.cancel();
        }
        if let Some(attempt) = self.bootstrap_attempt.take() {
            attempt.cancel();
        }
        self.operation = None;
        self.candidate = None; // Dropping the direct verifier revokes outstanding native signing leases.
        self.busy = false;
        self.ssh_submitted = false;
        self.done = false;
        self.comparison.update(cx, |input, cx| {
            input.clear(cx);
        });
        self.status = "No server has been added by this attempt.".into();
    }
    fn change_method(&mut self, method: Method, cx: &mut Context<Self>) {
        if self.method == method {
            return;
        }
        self.cancel(cx);
        self.method = method;
        self.address.update(cx, |input, cx| {
            input.clear(cx);
        });
        self.invitation.update(cx, |input, cx| {
            input.clear(cx);
        });
        self.status = match method {
            Method::Direct => "Enter an address and a single-use invitation from an already paired device.",
            Method::Ssh => "SSH setup uses OpenSSH host and account trust. Check the host before deliberately installing or reusing its server.",
        }.into();
    }
    fn current(&self, attempt: &EnrollmentAttempt) -> bool {
        self.attempt
            .as_ref()
            .is_some_and(|current| current.matches(attempt))
    }
    fn inspect(&mut self, cx: &mut Context<Self>) {
        if self.busy || self.done {
            return;
        }
        let Some(provider) = self.provider.clone() else {
            return;
        };
        let address = self.address.read(cx).value().trim().to_owned();
        if address.is_empty() || address.len() > 2048 || address.chars().any(char::is_control) {
            self.status = "Enter a server address or SSH host.".into();
            cx.notify();
            return;
        }
        self.cancel(cx);
        let Some(generation) = self.generation.checked_add(1) else {
            self.status = failure_message(PairingFailure::LimitExceeded.into()).into();
            cx.notify();
            return;
        };
        self.generation = generation;
        let attempt = EnrollmentAttempt::new(generation);
        let target = match self.method {
            Method::Direct => EnrollmentTarget::Direct {
                address,
                invitation: Zeroizing::new(
                    self.invitation.update(cx, |input, cx| input.take_value(cx)),
                ),
            },
            Method::Ssh => EnrollmentTarget::Ssh { host: address },
        };
        let task = provider.inspect(target, attempt.clone(), cx);
        self.attempt = Some(attempt.clone());
        self.busy = true;
        self.status = "Checking the selected server's prerequisites…".into();
        self.operation = Some(cx.spawn(async move |sheet, cx| {
            let result = task.await;
            let _ = sheet.update(cx, |sheet, cx| {
                if !sheet.current(&attempt) {
                    return;
                }
                sheet.busy = false;
                let candidate = result.and_then(|candidate| match candidate {
                    EnrollmentDiscovery::Direct(candidate)
                        if sheet.method == Method::Direct
                            && attempt.matches(&candidate.attempt) =>
                    {
                        let verifier = candidate.verifier()?;
                        Ok(Candidate::Direct {
                            candidate,
                            verifier,
                            submitted: false,
                        })
                    }
                    EnrollmentDiscovery::Ssh(candidate)
                        if sheet.method == Method::Ssh && attempt.matches(&candidate.attempt) =>
                    {
                        Ok(Candidate::Ssh(candidate))
                    }
                    _ => Err(PairingFailure::RouteChanged.into()),
                });
                match candidate {
                    Ok(candidate) => {
                        sheet.ssh_submitted = matches!(&candidate, Candidate::Ssh(candidate) if candidate.pending.is_some());
                        sheet.status = candidate_message(&candidate).into();
                        sheet.candidate = Some(candidate);
                    }
                    Err(error) => sheet.status = failure_message(error).into(),
                }
                cx.notify();
            });
        }));
        cx.notify();
    }
    fn approve(&mut self, cx: &mut Context<Self>) {
        if self.busy || self.done {
            return;
        }
        let Some(provider) = self.provider.clone() else {
            return;
        };
        let Some(attempt) = self.attempt.clone() else {
            return;
        };
        if attempt.validate().is_err() {
            return;
        }
        let Some(candidate) = self.candidate.as_mut() else {
            return;
        };
        let (task, expected) = match candidate {
            Candidate::Direct {
                candidate,
                verifier,
                submitted,
            } => {
                let compared = self.comparison.read(cx).value().trim();
                let approval = match candidate.approve(verifier, compared) {
                    Ok(approval) => approval,
                    Err(error) => {
                        self.status = failure_message(error).into();
                        cx.notify();
                        return;
                    }
                };
                *submitted = true;
                (
                    provider.enroll_direct(approval, cx),
                    Some(candidate.prepared.clone()),
                )
            }
            Candidate::Ssh(candidate) => {
                let task = if self.ssh_submitted {
                    let Some(request) = candidate.pending else {
                        self.status = "The original setup has no confirmed lookup identity. Check its status on the host before starting another setup.".into();
                        cx.notify();
                        return;
                    };
                    provider.resolve_bootstrap((**candidate).clone(), request, cx)
                } else {
                    let intent = match candidate.confirm() {
                        Ok(intent) => intent,
                        Err(error) => {
                            self.status = failure_message(error).into();
                            cx.notify();
                            return;
                        }
                    };
                    self.bootstrap_attempt = Some(intent.cancellation());
                    self.ssh_submitted = true;
                    provider.bootstrap(intent, (**candidate).clone(), cx)
                };
                (task, None)
            }
        };
        self.busy = true;
        self.status = "Waiting for a verified, durably saved pairing receipt…".into();
        self.operation = Some(cx.spawn(async move |sheet, cx| {
            let result = task.await;
            let _ = sheet.update(cx, |sheet, cx| {
                if !sheet.current(&attempt) {
                    return;
                }
                sheet.busy = false;
                let result = result.and_then(|enrollment| {
                    if !attempt.matches(&enrollment.attempt)
                        || expected.as_ref().is_some_and(|expected| {
                            expected != &enrollment.prepared || enrollment.bootstrap.is_some()
                        })
                    {
                        return Err(PairingFailure::IdentityMismatch.into());
                    }
                    if let Some(Candidate::Ssh(candidate)) = &sheet.candidate {
                        let matches = enrollment.bootstrap.as_ref().is_some_and(|outcome| {
                            outcome.server.route == candidate.facts.route
                                && candidate.pending.is_none_or(|request| request.artifact == outcome.server.approved_artifact_identity)
                                && match candidate.facts.registration {
                                    BootstrapRegistration::Running {
                                        pin,
                                        generation,
                                        artifact_identity,
                                        ..
                                    } => {
                                        (outcome.reused || candidate.pending.is_some())
                                            && pin == outcome.server.pin
                                            && generation == outcome.server.registration_generation
                                            && artifact_identity
                                                == outcome.server.approved_artifact_identity
                                    }
                                    BootstrapRegistration::Missing => !outcome.reused || candidate.pending.is_some(),
                                    _ => false,
                                }
                        });
                        if !matches {
                            return Err(PairingFailure::IdentityMismatch.into());
                        }
                    }
                    attempt.validate()?;
                    provider.publish(enrollment, cx)
                });
                match result {
                    Ok(()) => {
                        sheet.done = true;
                        sheet.status =
                            "Server added. Its existing work and network settings are unchanged."
                                .into();
                    }
                    Err(error) => {
                        if let EnrollmentFailure::BootstrapUnresolved(request) = error
                            && let Some(Candidate::Ssh(candidate)) = &mut sheet.candidate
                        {
                            let valid = !matches!(candidate.facts.registration, BootstrapRegistration::Running { artifact_identity, .. } if artifact_identity != request.artifact);
                            if valid { candidate.pending = Some(request); }
                        }
                        sheet.status = failure_message(error).into();
                    }
                }
                cx.notify();
            });
        }));
        cx.notify();
    }
    fn start(&mut self, cx: &mut Context<Self>) {
        if self.busy || self.done {
            return;
        }
        let Some(provider) = self.provider.clone() else {
            return;
        };
        let Some(Candidate::Ssh(candidate)) = self.candidate.take() else {
            return;
        };
        if !matches!(
            candidate.facts.registration,
            BootstrapRegistration::Stopped { .. }
        ) {
            self.candidate = Some(Candidate::Ssh(candidate));
            return;
        }
        let attempt = candidate.attempt.clone();
        if !self.current(&attempt) {
            return;
        }
        let task = provider.start(*candidate, cx);
        self.busy = true;
        self.status = "Starting the selected stopped server…".into();
        self.operation = Some(cx.spawn(async move |sheet, cx| {
            let result = task.await;
            let _ = sheet.update(cx, |sheet, cx| {
                if !sheet.current(&attempt) {
                    return;
                }
                sheet.busy = false;
                sheet.status = match result {
                    Ok(()) => "Start requested. Check Again before confirming setup.".into(),
                    Err(error) => failure_message(error).into(),
                };
                cx.notify();
            });
        }));
        cx.notify();
    }
}

fn candidate_message(candidate: &Candidate) -> &'static str {
    match candidate {
        Candidate::Direct { .. } => {
            "Compare this fingerprint with the server's owner through another trusted channel. Enter that fingerprint below; then confirm enrollment."
        }
        Candidate::Ssh(candidate) if candidate.pending.is_some() => {
            "The original setup is unresolved. Check Original Setup only reads its retained request."
        }
        Candidate::Ssh(candidate) => match candidate.facts.registration {
            BootstrapRegistration::Stopped { .. } => {
                "This server is stopped. Setup will not start it. Use Start Server, then Check Again."
            }
            BootstrapRegistration::Running { .. } => {
                "A compatible server already runs here, including headless installations. Setup reuses it without an update, restart, second server or network change."
            }
            _ => {
                "No server is installed. Set Up over SSH installs the verified account-service artifact and pairs this device. Enabling lingering may ask for an administrator password."
            }
        },
    }
}

fn input(
    selector: &'static str,
    label: &'static str,
    secret: bool,
    window: &mut Window,
    cx: &mut Context<ServerEnrollment>,
) -> Entity<TextInput> {
    cx.new(|cx| {
        TextInput::new(selector, label, String::new(), window, cx)
            .placeholder(label)
            .content_mode(if secret {
                TextInputContentMode::Obscured
            } else {
                TextInputContentMode::Plain
            })
            .input_length_limit(Some(if secret { 16 * 1024 } else { 2048 }))
            .return_behavior(TextInputReturnBehavior::Propagate)
            .escape_behavior(TextInputEscapeBehavior::Propagate)
            .debug_selector(selector)
    })
}

fn field(
    input: Entity<TextInput>,
    label: &'static str,
    appearance: &ChromeAppearance,
) -> AnyElement {
    div()
        .flex()
        .flex_col()
        .gap(appearance.spacing(4.0))
        .child(
            div()
                .chrome_text(appearance.typography.style(TextRole::Secondary))
                .child(label),
        )
        .child(input)
        .into_any_element()
}

impl Render for ServerEnrollment {
    fn render(&mut self, _: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let appearance = shared_chrome(cx);
        let colors = appearance.host_colors(spaceterm_ui::ControlHost::Floating);
        let method = self.method;
        let announcement = self.status.clone();
        let owner = cx.weak_entity();
        let check = cx.weak_entity();
        let approve = cx.weak_entity();
        let start = cx.weak_entity();
        let fingerprint = self
            .candidate
            .as_ref()
            .and_then(|candidate| match candidate {
                Candidate::Direct { verifier, .. } => Some(verifier.fingerprint()),
                _ => None,
            });
        let compared = self.comparison.read(cx).value().trim();
        let direct_approved = fingerprint
            .as_deref()
            .is_some_and(|fingerprint| fingerprint == compared);
        let stopped = matches!(&self.candidate, Some(Candidate::Ssh(candidate)) if matches!(candidate.facts.registration, BootstrapRegistration::Stopped { .. }));
        let direct_submitted = matches!(
            &self.candidate,
            Some(Candidate::Direct {
                submitted: true,
                ..
            })
        );
        let ready = !self.busy && !self.done && self.provider.is_some();
        let submitted = direct_submitted || self.ssh_submitted;
        div()
            .debug_selector(|| "settings-server-enrollment".to_owned())
            .flex()
            .flex_col()
            .w_full()
            .gap(appearance.spacing(12.0))
            .chrome_text(appearance.typography.style(TextRole::Body))
            .text_color(gpui_color(colors.text))
            .child(
                SegmentedControl::new(
                    "settings-server-enrollment-method",
                    "Connection method",
                    &method,
                    vec![
                        SegmentedOption::new(Method::Direct, "Direct connection")
                            .debug_selector("settings-server-enrollment-direct"),
                        SegmentedOption::new(Method::Ssh, "SSH setup")
                            .debug_selector("settings-server-enrollment-ssh"),
                    ],
                )
                .expect("two connection methods are within the bounded option set")
                .on_change(move |change, _, cx| {
                    let _ =
                        owner.update(cx, |sheet, cx| sheet.change_method(*change.requested(), cx));
                }),
            )
            .child(field(
                self.address.clone(),
                if method == Method::Direct {
                    "Server address"
                } else {
                    "SSH host from OpenSSH configuration"
                },
                &appearance,
            ))
            .when(method == Method::Direct && !direct_submitted, |view| {
                view.child(field(
                    self.invitation.clone(),
                    "Single-use pairing invitation",
                    &appearance,
                ))
            })
            .child(
                Button::new(
                    "settings-server-enrollment-check",
                    if direct_submitted {
                        "Check Original Enrollment"
                    } else if self.ssh_submitted {
                        "Check Original Setup"
                    } else if self.attempt.is_some() {
                        "Check Again"
                    } else {
                        "Check Server"
                    },
                )
                .variant(ButtonVariant::Outline)
                .tab_stop(true)
                .disabled(!ready)
                .debug_selector("settings-server-enrollment-check")
                .on_activate(move |_, _, cx| {
                    let _ = check.update(cx, |sheet, cx| {
                        if submitted {
                            sheet.approve(cx);
                        } else {
                            sheet.inspect(cx);
                        }
                    });
                }),
            )
            .children(fingerprint.map(|fingerprint| {
                div()
                    .flex()
                    .flex_col()
                    .gap(appearance.spacing(6.0))
                    .child(
                        div()
                            .id("settings-server-enrollment-fingerprint")
                            .role(accesskit::Role::Group)
                            .aria_label("Server fingerprint")
                            .debug_selector(|| "settings-server-enrollment-fingerprint".to_owned())
                            .child(gpui::Text::new(
                                "settings-server-enrollment-fingerprint-text".into(),
                                SharedString::from(fingerprint),
                            )),
                    )
                    .child(field(
                        self.comparison.clone(),
                        "Fingerprint received through another trusted channel",
                        &appearance,
                    ))
            }))
            .child(
                div()
                    .id("settings-server-enrollment-status")
                    .role(accesskit::Role::Status)
                    .a11y_synthetic_children(move |builder| {
                        let mut status = accesskit::Node::new(accesskit::Role::Status);
                        status.set_label(announcement.as_ref());
                        status.set_live(accesskit::Live::Polite);
                        builder.push_child(builder.synthetic_node_id("enrollment-status"), status);
                    })
                    .debug_selector(|| "settings-server-enrollment-status".to_owned())
                    .whitespace_normal()
                    .chrome_text(appearance.typography.style(TextRole::Secondary))
                    .text_color(gpui_color(colors.text_secondary))
                    .child(gpui::Text::new(
                        "settings-server-enrollment-status-text".into(),
                        self.status.clone(),
                    )),
            )
            .when(stopped, |view| {
                view.child(
                    Button::new("settings-server-enrollment-start", "Start Server")
                        .tab_stop(true)
                        .disabled(!ready)
                        .debug_selector("settings-server-enrollment-start")
                        .on_activate(move |_, _, cx| {
                            let _ = start.update(cx, |sheet, cx| sheet.start(cx));
                        }),
                )
            })
            // After submission the check button above is the single Check Original control.
            .when(self.candidate.is_some() && !stopped && !submitted, |view| {
                view.child(
                    Button::new(
                        "settings-server-enrollment-confirm",
                        if method == Method::Ssh {
                            "Set Up over SSH"
                        } else {
                            "Confirm Fingerprint and Pair"
                        },
                    )
                    .tab_stop(true)
                    .disabled(!ready || (method == Method::Direct && !direct_approved))
                    .debug_selector("settings-server-enrollment-confirm")
                    .on_activate(move |_, _, cx| {
                        let _ = approve.update(cx, |sheet, cx| sheet.approve(cx));
                    }),
                )
            })
    }
}

impl SettingsWindow {
    pub(super) fn render_server_enrollment_action(&self, cx: &mut Context<Self>) -> AnyElement {
        let owner = cx.weak_entity();
        action_button(
            "settings-server-add",
            "Add Server…",
            true,
            move |window, cx| {
                let _ = owner.update(cx, |settings, cx| {
                    settings.open_server_enrollment(window, cx)
                });
            },
        )
        .into_any_element()
    }
    fn open_server_enrollment(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        let sheet = cx.new(|cx| ServerEnrollment::new(window, cx));
        let focus = sheet.read(cx).address.read(cx).focus_handle();
        let closing = sheet.clone();
        let dialog = Dialog::new(ModalId::new("settings-server-enrollment"), "Add server", "Add Server",
            vec![ModalAction::new((), "Done", ModalActionRole::Cancel, "settings-server-enrollment-done")],
            DialogInitialFocus::Body(focus))
            .description("Adding a server pairs this device. Ordinary reconnect never installs a server or enrolls a revoked device.")
            .body(sheet);
        if dialog
            .present(
                window,
                cx,
                |_, _, _| DialogCloseDecision::Allow,
                move |_, cx| {
                    closing.update(cx, |sheet, cx| {
                        sheet.cancel(cx);
                        sheet.invitation.update(cx, |input, cx| {
                            input.clear(cx);
                        });
                    });
                },
            )
            .is_err()
        {
            eprintln!("failed to present the SpaceTerm Add Server sheet");
        }
    }
}

fn failure_message(error: EnrollmentFailure) -> &'static str {
    match error {
        EnrollmentFailure::BootstrapUnresolved(_) => {
            "The setup reply is unresolved. Check Original Setup reads only the retained request; it will not install or enroll again."
        }
        EnrollmentFailure::CredentialStorageLocked => {
            "Unlock the native credential store, then Check Again."
        }
        EnrollmentFailure::ProviderUnavailable => {
            "Server enrollment is unavailable in this build. No server has been changed."
        }
        EnrollmentFailure::Bootstrap(BootstrapFailureClass::Pairing(error))
        | EnrollmentFailure::Pairing(error) => match error {
            PairingFailure::FingerprintMismatch => {
                "The fingerprints do not match. Verify the server with its owner before pairing."
            }
            PairingFailure::ExplicitStartRequired => {
                "This server is stopped. Use Start Server, then Check Again. Setup will not start it implicitly."
            }
            PairingFailure::Incompatible => {
                "This server is incompatible. Setup will not update it or install a second server."
            }
            PairingFailure::UnsupportedTarget => {
                "This host's operating system, architecture or libc is unsupported. Nothing was installed."
            }
            PairingFailure::ServiceManagerUnavailable => {
                "The account service manager is unavailable. Restore it, then Check Again."
            }
            PairingFailure::StorageUnavailable | PairingFailure::CredentialUnavailable => {
                "Required private storage is unavailable. Restore it, then Check Again."
            }
            PairingFailure::AuthorizationRequired => {
                "A single-use pairing invitation is required. Ask an already paired device for a new invitation."
            }
            PairingFailure::AuthorizationDenied => {
                "Authorization was denied. No fallback authorization will be used."
            }
            PairingFailure::AuthorizationUnavailable => {
                "Administrator authorization is unavailable. Restore the authorization agent, then Check Again."
            }
            PairingFailure::RouteChanged | PairingFailure::IdentityMismatch => {
                "The attempt, route, server or credential changed. Check the selected server again."
            }
            PairingFailure::Cancelled => "Setup was cancelled. No background enrollment will run.",
            PairingFailure::Offline
            | PairingFailure::TimedOut
            | PairingFailure::RecoveryRequired
            | PairingFailure::RevocationUnconfirmed => {
                "The reply is unresolved. Check the original enrollment; do not issue a replacement request."
            }
            PairingFailure::PairingRevoked => {
                "This pairing was revoked. Ordinary reconnect cannot enroll it again."
            }
            _ => "The server could not be added. No unverified pairing has been published.",
        },
        EnrollmentFailure::Bootstrap(error) => match error {
            BootstrapFailureClass::StorageLocked => {
                "Unlock the server's private storage, then Check Again."
            }
            BootstrapFailureClass::LoginSessionUnavailable => {
                "The remote account has no GUI login session. Log in there, then Check Again."
            }
            BootstrapFailureClass::LingerUnavailable => {
                "Lingering is unavailable. Restore login-manager access, then Check Again."
            }
            BootstrapFailureClass::MissingAuthorizationAgent => {
                "The scoped linger authorization agent is unavailable. Restore it, then Check Again."
            }
            BootstrapFailureClass::BackgroundItemsSuppressed => {
                "SpaceTerm background items are disabled. Enable them on the server's host, then Check Again."
            }
            BootstrapFailureClass::BootstrapTrustUnavailable => {
                "A verified server artifact is unavailable. Nothing was installed."
            }
            _ => "The host prerequisite check failed. Nothing was installed.",
        },
    }
}
